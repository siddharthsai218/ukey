#!/usr/bin/env python3
"""Device pairing and token authentication for uKey.

Prevents unauthorized devices on the local network (Wi-Fi) from hijacking or
interacting with the uKey daemon.

Security model:
1. First time only: The user authorizes their phone using a 6-digit PIN
   generated by the daemon (viewable via `ukeyctl pair` or the web dashboard).
2. The daemon issues a cryptographically secure 256-bit device token.
3. The phone saves this token in secure storage.
4. Every subsequent connection: The phone presents the token automatically in
   the initial handshake (<5ms). No PIN is ever entered again.
5. Strangers on the same Wi-Fi without a valid token are immediately dropped.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import secrets
import tempfile
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Optional

LOG = logging.getLogger("ukey.pairing")

DEFAULT_PAIRING_PATH = "~/.config/ukey/pairing.json"


@dataclass
class PairedDevice:
    device_name: str
    token_hash: str
    created_at: float
    last_seen_at: float = 0.0

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class PairingManager:
    """Manages the 6-digit pairing PIN and persistent authorized device tokens."""

    def __init__(self, path: Optional[Path | str] = None) -> None:
        if path is None:
            self.path = Path(os.environ.get("UKEY_PAIRING_PATH", DEFAULT_PAIRING_PATH)).expanduser()
        else:
            self.path = Path(path).expanduser()

        self._pin: str = ""
        self._pin_created_at: float = 0.0
        self._paired_devices: dict[str, PairedDevice] = {}  # token_hash -> PairedDevice
        self.load()

    @property
    def paired_count(self) -> int:
        return len(self._paired_devices)

    def load(self) -> None:
        """Load paired devices and active PIN from disk."""
        if not self.path.exists():
            return
        try:
            with open(self.path, "r", encoding="utf-8") as f:
                data = json.load(f)
            self._pin = data.get("active_pin", "")
            self._pin_created_at = float(data.get("pin_created_at", 0.0))
            self._paired_devices.clear()
            for thash, dev in data.get("paired_devices", {}).items():
                self._paired_devices[thash] = PairedDevice(
                    device_name=dev.get("device_name", "Unknown Phone"),
                    token_hash=thash,
                    created_at=float(dev.get("created_at", 0.0)),
                    last_seen_at=float(dev.get("last_seen_at", 0.0)),
                )
        except Exception as exc:
            LOG.warning("Failed to load pairing data from %s: %s", self.path, exc)

    def save(self) -> None:
        """Atomically persist pairing data to disk."""
        self.path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "active_pin": self._pin,
            "pin_created_at": self._pin_created_at,
            "paired_devices": {thash: dev.to_dict() for thash, dev in self._paired_devices.items()},
        }
        temp_file = tempfile.NamedTemporaryFile(
            mode="w",
            dir=str(self.path.parent),
            delete=False,
            encoding="utf-8",
        )
        try:
            json.dump(payload, temp_file, indent=2)
            temp_file.flush()
            os.fsync(temp_file.fileno())
            temp_file.close()
            os.replace(temp_file.name, self.path)
            os.chmod(self.path, 0o600)  # Private credentials
        except Exception:
            if os.path.exists(temp_file.name):
                os.unlink(temp_file.name)
            raise

    def get_or_create_pin(self, force_new: bool = False) -> str:
        """Return the active 6-digit pairing PIN, generating one if needed."""
        # PIN expires after 15 minutes unless reused
        now = time.time()
        if force_new or not self._pin or (now - self._pin_created_at > 900):
            self._pin = f"{secrets.randbelow(900000) + 100000:06d}"
            self._pin_created_at = now
            self.save()
            LOG.info("Generated new 6-digit pairing PIN: %s", self._pin)
        return self._pin

    @staticmethod
    def hash_token(token: str) -> str:
        return hashlib.sha256(token.encode("utf-8")).hexdigest()

    def pair_with_pin(self, pin: str, device_name: str = "Android Device") -> Optional[str]:
        """Verify the 6-digit PIN and issue a permanent 256-bit device token."""
        clean_pin = pin.strip().replace(" ", "")
        if not self._pin or clean_pin != self._pin:
            LOG.warning("Pairing attempt failed: invalid PIN provided")
            return None

        # Expire the PIN once used for security
        self._pin = ""
        self._pin_created_at = 0.0

        # Generate persistent 256-bit device token
        raw_token = secrets.token_hex(32)
        thash = self.hash_token(raw_token)

        self._paired_devices[thash] = PairedDevice(
            device_name=device_name[:64],
            token_hash=thash,
            created_at=time.time(),
            last_seen_at=time.time(),
        )
        self.save()
        LOG.info("Successfully paired new device '%s' (hash: %s...)", device_name, thash[:8])
        return raw_token

    def verify_token(self, token: str) -> bool:
        """Check if the provided device token is authorized."""
        if not token or not isinstance(token, str):
            return False
        thash = self.hash_token(token.strip())
        device = self._paired_devices.get(thash)
        if device is not None:
            device.last_seen_at = time.time()
            # Do not fsync on every single request, but update in memory
            return True
        return False

    def revoke_device(self, token_prefix: str) -> bool:
        """Revoke authorization for a device by token hash prefix."""
        for thash in list(self._paired_devices.keys()):
            if thash.startswith(token_prefix):
                del self._paired_devices[thash]
                self.save()
                LOG.info("Revoked authorization for device with hash prefix %s", token_prefix)
                return True
        return False

    def revoke_all(self) -> None:
        """Revoke all paired devices."""
        self._paired_devices.clear()
        self.save()
        LOG.info("Revoked all paired devices")

    def list_devices(self) -> list[dict[str, Any]]:
        """Return a user-facing list of authorized devices."""
        result = []
        for thash, dev in self._paired_devices.items():
            result.append({
                "device_name": dev.device_name,
                "id": thash[:12],
                "created_at": dev.created_at,
                "last_seen_at": dev.last_seen_at,
            })
        return sorted(result, key=lambda x: x["created_at"], reverse=True)
